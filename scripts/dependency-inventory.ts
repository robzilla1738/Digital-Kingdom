/** Production dependency inventory and license notices: docs/THIRD_PARTY_NOTICES.md (pnpm licenses list --prod). */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
const ROOT = resolve(import.meta.dirname, "..");
type Pkg = { name: string; versions: string[]; license: string; homepage?: string };
const data = JSON.parse(execFileSync("pnpm", ["licenses", "list", "--json", "--prod"], { cwd: ROOT, encoding: "utf8", maxBuffer: 64 << 20 })) as Record<string, Pkg[]>;
const ALLOWED = new Set(["MIT", "Apache-2.0", "ISC", "BSD-2-Clause", "BSD-3-Clause", "BlueOak-1.0.0", "0BSD", "CC0-1.0", "Unlicense"]);
const rows = Object.values(data).flat().sort((a, b) => a.name.localeCompare(b.name));
const bad = rows.filter((r) => !ALLOWED.has(r.license));
const md = [
  "# Third-party notices", "",
  "Production dependencies of the Digital Kingdom workspace, generated by `pnpm deps:inventory` from the lockfile.",
  `Licenses allowed without review: ${[...ALLOWED].join(", ")}. Anything else fails CI until reviewed.`, "",
  `${rows.length} packages.`, "", "| Package | Version | License |", "|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.versions.join(", ")} | ${r.license} |`), "",
].join("\n");
writeFileSync(join(ROOT, "docs/THIRD_PARTY_NOTICES.md"), md);
console.log(`${rows.length} production packages; ${bad.length} need license review`);
if (bad.length) { console.error(bad.map((b) => `${b.name}: ${b.license}`).join("\n")); process.exit(1); }
