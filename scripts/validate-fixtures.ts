/**
 * Port of the blueprint's validate_examples.py, extended to the v0.2 demo corpus. Validates schemas,
 * graph reference integrity, scene membership/zone/module constraints, mutation rejections, and that every
 * delivery is either accepted, a counted duplicate, or a counted rejection. Writes docs/VALIDATION_REPORT.md.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { validateEventSchema, validateGraphSchema, type Graph, type SceneProposal } from "../packages/contracts/src/index.ts";
import { validateGraph } from "../packages/graph-core/src/index.ts";
import { compileScene, defaultProposal, validateProposal } from "../packages/scene-compiler/src/index.ts";
import { evaluate, processDeliveries, type Delivery, type SourceConfig } from "../packages/detections/src/index.ts";

const read = (p: string) => JSON.parse(readFileSync(new URL(`../${p}`, import.meta.url), "utf8"));
const checks: string[] = [];
const must = (cond: boolean, label: string) => { if (!cond) throw new Error("FAILED: " + label); checks.push(label); };

// legacy blueprint examples (v0.1)
const lg = read("docs/blueprint/examples/graph.json") as Graph;
const lp = read("docs/blueprint/examples/scene-proposal.json") as SceneProposal;
must(validateGraphSchema(lg).ok && validateGraph(lg, { knownEvidenceRefs: new Set(Object.keys(read("docs/blueprint/examples/evidence.json").records)) }).ok, "Blueprint v0.1 graph validates, provenance resolves");
must(validateProposal(lg, lp).ok, "Blueprint v0.1 scene proposal passes membership, zone and module constraints");
must((read("docs/blueprint/examples/events.json") as unknown[]).every((e) => validateEventSchema(e).ok), "Blueprint v0.1 events validate");
const mutate = (fn: (p: SceneProposal & Record<string, unknown>) => void) => { const p = JSON.parse(JSON.stringify(lp)); fn(p); return validateProposal(lg, p).ok; };
must(!mutate((p) => { p.placements[0]!.asset_id = "invented"; }), "Rejected invented asset");
must(!mutate((p) => { p.placements.push(p.placements[0]!); }), "Rejected duplicate membership");
must(!mutate((p) => { p.placements[0]!.zone_id = "data"; }), "Rejected unauthorized zone");
must(!mutate((p) => { p.placements[0]!.module_id = "vault"; }), "Rejected incompatible module");
must(!mutate((p) => { p.attack_status = "compromised"; }), "Rejected model-supplied security status");
must(!mutate((p) => { p.script = "x"; }), "Rejected executable-content field");
must(!mutate((p) => { p.graph_revision = "wrong"; }), "Rejected graph revision mismatch");
must(!mutate((p) => { p.placements.pop(); }), "Rejected omitted asset");

// v0.2 demo corpus
const g = read("fixtures/demo/graph.json") as Graph;
const sources = read("fixtures/demo/sources.json") as SourceConfig[];
const deliveries = read("fixtures/demo/deliveries.json") as Delivery[];
must(validateGraph(g).ok, `Demo graph validates (${g.assets.length} assets, ${g.relationships.length} relationships)`);
const r = processDeliveries(g, sources, deliveries);
const rejected = Object.values(r.stats.rejected).reduce((a, b) => a + b, 0);
must(r.stats.accepted + r.stats.duplicates + rejected === deliveries.length, `All ${deliveries.length} deliveries accounted for (${r.stats.accepted} accepted, ${r.stats.duplicates} duplicate, ${rejected} rejected)`);
must(r.events.every((e) => validateEventSchema(e).ok), "Every normalized event validates against the event schema");
const ev = evaluate(g, r.events, { sources });
const ids = new Set(r.events.map((e) => e.id));
must(ev.findings.every((f) => f.event_ids.length > 0 && [...f.event_ids, ...f.counterevidence_event_ids].every((i) => ids.has(i))), `All ${ev.findings.length} findings resolve to recorded events`);
const s1 = compileScene(g, defaultProposal(g, 1)), s2 = compileScene(g, defaultProposal(g, 1));
must(s1.digest === s2.digest && s1.rooms.length === g.assets.length, "Scene compile is deterministic and places every asset exactly once");

const report = `# Fixture validation report\n\nGenerated by \`pnpm validate:fixtures\` against synthetic fixtures only.\n\n${checks.map((c) => `- PASS: ${c}`).join("\n")}\n\nThis validates contracts, fixtures and engine invariants. Live-source behaviour, throughput, and rendering are covered by the test suite and docs/VERIFICATION.md, not by this script.\n`;
writeFileSync(new URL("../docs/VALIDATION_REPORT.md", import.meta.url), report);
console.log(report);
