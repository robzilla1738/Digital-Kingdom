/** Real seeded-server checks; expansion changes presentation, not the selected evidence instance. */
import { test, expect } from '@playwright/test';
import type { Finding } from '@dk/contracts';
import { createRedesignHarness, loginRedesign, captureRedesign, writeRedesignEvidence, type RedesignHarness } from './redesign-harness.ts';
let harness: RedesignHarness;
let findings: Finding[];
const reports: unknown[] = [];
test.beforeAll(async () => { harness = await createRedesignHarness(); findings = (await harness.api('GET', '/api/projects/demo-castle/findings')).json; });
test.afterAll(async () => { writeRedesignEvidence('expanded-investigation-verification.json', reports); await harness?.close(); });
for (const width of [1440, 390, 320]) {
  test(`Expanded investigation ${width}px: primary detail preserves evidence and draft, filtered queue, scroll and return focus`, async ({ browser }) => {
    const { context, page } = await loginRedesign(browser, harness, { viewport: { width, height: 900 } });
    try {
      const headerTargets = await page.evaluate(() => {
        const project = document.querySelector<HTMLSelectElement>('select[aria-label="Project"]')!;
        const auth = document.querySelector<HTMLButtonElement>('.header-auth button')!;
        const p = project.getBoundingClientRect(), a = auth.getBoundingClientRect();
        return { project: p.toJSON(), auth: a.toJSON(), overlap: p.left < a.right && p.right > a.left && p.top < a.bottom && p.bottom > a.top, projectHit: project.contains(document.elementFromPoint(p.left + p.width / 2, p.top + p.height / 2)), authHit: auth.contains(document.elementFromPoint(a.left + a.width / 2, a.top + a.height / 2)) };
      });
      expect(headerTargets.overlap).toBe(false); expect(headerTargets.projectHit).toBe(true); expect(headerTargets.authHit).toBe(true);
      if (width < 768) { expect(headerTargets.project.height).toBeGreaterThanOrEqual(44); expect(headerTargets.auth.height).toBeGreaterThanOrEqual(44); }
      const target = findings.find(finding => finding.counterevidence_event_ids.length > 0)!;
      let evidenceRequests = 0;
      page.on('request', request => { if (new URL(request.url()).pathname.endsWith(`/findings/${target.id}/evidence`)) evidenceRequests++; });
      await page.getByRole('button', { name: 'Investigate', exact: true }).click();
      const results = page.locator('.findings-workspace');
      if (width < 768) await page.getByRole('button', { name: 'Filter findings', exact: true }).click();
      await results.getByLabel('Severity', { exact: true }).selectOption(target.severity);
      await results.getByLabel('Lifecycle', { exact: true }).selectOption('');
      await results.getByRole('searchbox').fill(' ');
      const ids = await results.locator('[data-finding-id]').evaluateAll(elements => elements.map(element => element.getAttribute('data-finding-id')!));
      expect(ids.length).toBeGreaterThan(1);
      const invoker = results.locator(`[data-finding-id="${target.id}"]`);
      await results.evaluate(element => { element.scrollTop = 180; });
      await invoker.scrollIntoViewIfNeeded();
      const beforeSelectScroll = await results.evaluate(element => element.scrollTop);
      expect(beforeSelectScroll).toBeGreaterThan(0);
      await invoker.click();
      const pane = page.locator('aside.evidence');
      await expect(pane).toHaveAttribute('data-selection-id', target.id);
      await expect(pane.getByTestId('evidence-count')).toContainText('All referenced stored records');
      const expectedScroll = width >= 1280 ? await results.evaluate(element => element.scrollTop) : beforeSelectScroll;
      await pane.getByRole('tab', { name: /^Counterevidence/ }).click();
      const compare = pane.getByLabel('Compare supporting and counterevidence together', { exact: true });
      await compare.uncheck();
      const raw = pane.locator('[data-evidence-role="counter"]').first().getByTestId('evidence-card-raw');
      await raw.locator('summary').click();
      const draft = 'Synthetic unsaved draft: expansion must retain this text. Do not submit.';
      await pane.getByLabel('Analyst note', { exact: true }).fill(draft);
      const requestCount = evidenceRequests;
      expect(requestCount).toBeGreaterThan(0);
      await page.evaluate(() => { const w = window as any; w.expansionBefore = { pane: document.querySelector('aside.evidence'), title: document.querySelector('aside.evidence .ev-title'), card: document.querySelector('aside.evidence [data-evidence-role="counter"]'), note: document.querySelector('textarea[aria-label="Analyst note"]') }; });
      await pane.getByRole('button', { name: 'Expand investigation', exact: true }).click();
      await expect(pane).toHaveAttribute('data-expanded', 'true');
      await expect(pane).toBeFocused();
      await expect(pane).toHaveAttribute('role', 'region');
      await expect(page.getByRole('dialog')).toHaveCount(0);
      await expect(page.getByRole('separator', { name: 'Resize inspector' })).toBeHidden();
      const bounds = await pane.boundingBox(), mainBounds = await page.locator('.workspace-content').boundingBox();
      expect(bounds!.width).toBeGreaterThanOrEqual(mainBounds!.width - 2);
      if (width >= 1280) expect(bounds!.width).toBeGreaterThan(1100);
      await expect(results).toBeHidden();
      const sameNodes = await page.evaluate(() => { const before = (window as any).expansionBefore; return before.pane === document.querySelector('aside.evidence') && before.title === document.querySelector('aside.evidence .ev-title') && before.card === document.querySelector('aside.evidence [data-evidence-role="counter"]') && before.note === document.querySelector('textarea[aria-label="Analyst note"]'); });
      expect(sameNodes).toBe(true);
      await expect(compare).not.toBeChecked();
      await expect(pane.getByRole('tab', { name: /^Counterevidence/ })).toHaveAttribute('aria-selected', 'true');
      await expect(raw).toHaveAttribute('open', '');
      await expect(pane.getByLabel('Analyst note', { exact: true })).toHaveValue(draft);
      expect(evidenceRequests).toBe(requestCount);
      await expect(pane.getByTestId('finding-queue-position')).toHaveText(`Finding ${ids.indexOf(target.id) + 1} of ${ids.length} matching findings`);
      await captureRedesign(page, `expanded-investigation-${width}`);
      await pane.getByRole('button', { name: 'Return to results', exact: true }).click();
      await expect(results).toBeVisible(); await expect(pane).toBeHidden(); await expect(invoker).toBeFocused();
      await expect.poll(() => results.evaluate(element => element.scrollTop)).toBe(expectedScroll);
      await expect(results.getByLabel('Severity', { exact: true })).toHaveValue(target.severity);
      await expect(results.getByLabel('Lifecycle', { exact: true })).toHaveValue('');
      await expect(results.getByRole('searchbox')).toHaveValue(' ');
      expect(await results.locator('[data-finding-id]').evaluateAll(elements => elements.map(element => element.getAttribute('data-finding-id')))).toEqual(ids);
      await invoker.click();
      await expect(pane.getByLabel('Analyst note', { exact: true })).toHaveValue(draft);
      await expect(raw).toHaveAttribute('open', '');
      const expand = pane.getByRole('button', { name: 'Expand investigation', exact: true });
      await expand.focus(); await page.keyboard.press('Enter'); await expect(pane).toBeFocused();
      expect(evidenceRequests).toBe(requestCount);
      const index = ids.indexOf(target.id), next = index < ids.length - 1;
      await pane.getByRole('button', { name: next ? 'Next finding' : 'Previous finding', exact: true }).click();
      const adjacent = ids[index + (next ? 1 : -1)]!;
      await expect(pane).toHaveAttribute('data-selection-id', adjacent);
      await expect(pane).toHaveAttribute('data-expanded', 'true'); await expect(pane).toBeFocused();
      await expect(pane.getByTestId('finding-queue-position')).toHaveText(`Finding ${ids.indexOf(adjacent) + 1} of ${ids.length} matching findings`);
      await pane.getByRole('button', { name: next ? 'Previous finding' : 'Next finding', exact: true }).click();
      await expect(pane).toHaveAttribute('data-selection-id', target.id);
      await pane.getByRole('button', { name: 'Return to results', exact: true }).click();
      await expect(results).toBeVisible(); await expect(invoker).toBeFocused();
      await expect.poll(() => results.evaluate(element => element.scrollTop)).toBe(expectedScroll);
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      reports.push({ width, headerTargets, actualDetailWidth: bounds!.width, mainContentWidth: mainBounds!.width, sameMountedEvidenceDraftAndCard: sameNodes, noExtraEvidenceFetchOnExpansionOrReturn: true, filteredIds: ids, originalScrollTop: expectedScroll, restoredScrollTop: await results.evaluate(element => element.scrollTop), explicitQueueNeighbor: adjacent, expandedKeyboardFocusAndReturnInvokerFocus: true, result: 'passed' });
    } finally { await context.close(); }
  });
}

test('Expanded transitions: Kingdom keeps its finding instance; outside-filter and empty queues are honest; horizontal results scroll returns', async ({ browser }) => {
  const { page, context } = await loginRedesign(browser, harness, { viewport: { width: 1024, height: 800 } });
  try {
    const target = findings.find(finding => finding.counterevidence_event_ids.length > 0)!;
    await page.locator(`.sidebar [data-finding-id="${target.id}"]`).click();
    const pane = page.locator('aside.evidence');
    await expect(pane.getByTestId('evidence-count')).toContainText('All referenced stored records');
    const draft = 'Synthetic Kingdom-to-expanded continuity draft; not submitted.';
    await pane.getByLabel('Analyst note', { exact: true }).fill(draft);
    await page.evaluate(() => { (window as any).kingdomFinding = document.querySelector('aside.evidence .ev-title'); });
    await pane.getByRole('button', { name: 'Expand investigation', exact: true }).click();
    await expect(pane).toHaveAttribute('data-expanded', 'true');
    await expect(page.getByRole('button', { name: 'Investigate', exact: true })).toHaveAttribute('aria-current', 'page');
    expect(await page.evaluate(() => (window as any).kingdomFinding === document.querySelector('aside.evidence .ev-title'))).toBe(true);
    await expect(pane.getByLabel('Analyst note', { exact: true })).toHaveValue(draft);
    await pane.getByRole('button', { name: 'Return to results', exact: true }).click();
    const results = page.locator('.findings-workspace');
    const other = findings.find(finding => finding.id !== target.id)!;
    await results.getByRole('searchbox').fill(other.id);
    await expect(results.locator('[data-finding-id]')).toHaveCount(1);
    await results.locator('.pinned-selection button').click();
    await pane.getByRole('button', { name: 'Expand investigation', exact: true }).click();
    await expect(pane.getByTestId('finding-queue-position')).toContainText('outside current filters · 1 matches');
    await expect(pane.getByRole('button', { name: 'Previous finding', exact: true })).toBeDisabled();
    await pane.getByRole('button', { name: 'Next finding', exact: true }).click();
    await expect(pane).toHaveAttribute('data-selection-id', other.id);
    await expect(pane.getByTestId('finding-queue-position')).toHaveText('Finding 1 of 1 matching findings');
    await expect(pane.getByRole('button', { name: 'Next finding', exact: true })).toBeDisabled();
    await pane.getByRole('button', { name: 'Return to results', exact: true }).click();
    await results.getByRole('searchbox').fill('no-records-match-this-synthetic-test');
    await expect(results.locator('[data-finding-id]')).toHaveCount(0);
    await results.locator('.pinned-selection button').click();
    await pane.getByRole('button', { name: 'Expand investigation', exact: true }).click();
    await expect(pane.getByTestId('finding-queue-position')).toContainText('0 matches. No matching findings to navigate.');
    await expect(pane.getByRole('button', { name: 'Previous finding', exact: true })).toBeDisabled();
    await expect(pane.getByRole('button', { name: 'Next finding', exact: true })).toBeDisabled();
    await expect(pane).toHaveAttribute('data-selection-id', other.id);
    await pane.getByRole('button', { name: 'Return to results', exact: true }).click();
    await results.getByRole('searchbox').fill('');
    const table = results.locator('.table-scroll');
    const horizontalBefore = await table.evaluate(element => { element.scrollLeft = Math.min(80, element.scrollWidth - element.clientWidth); return { left: element.scrollLeft, max: element.scrollWidth - element.clientWidth }; });
    expect(horizontalBefore.max).toBeGreaterThan(0); expect(horizontalBefore.left).toBeGreaterThan(0);
    await results.locator(`[data-finding-id="${target.id}"]`).click();
    await pane.getByRole('button', { name: 'Expand investigation', exact: true }).click();
    await pane.getByRole('button', { name: 'Return to results', exact: true }).click();
    const horizontalAfter = await table.evaluate(element => ({ left: element.scrollLeft, max: element.scrollWidth - element.clientWidth }));
    expect(horizontalAfter.left).toBe(Math.min(horizontalBefore.left, horizontalAfter.max));
    reports.push({ transition: 'Kingdom → main-area investigation → filtered results', sameFindingInstance: true, nonemptyOutsideFilterQueue: 'explicitly opens first matching finding', emptyOutsideFilterQueue: 'both controls disabled, no matching findings disclosed', horizontalBefore, horizontalAfter, result: 'passed' });
  } finally { await context.close(); }
});
