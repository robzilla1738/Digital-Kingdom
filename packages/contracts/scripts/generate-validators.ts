/**
 * Precompiles the JSON Schemas into standalone ESM validators (no runtime `new Function`), so the
 * browser bundle runs under a strict Content-Security-Policy. Run after editing any schema:
 *   pnpm generate:validators
 */
import Ajv2020Mod from "ajv/dist/2020.js";
import addFormatsMod from "ajv-formats";
import standaloneMod from "ajv/dist/standalone/index.js";
import { readFileSync, writeFileSync } from "node:fs";

const Ajv2020 = ((Ajv2020Mod as unknown as { default?: unknown }).default ?? Ajv2020Mod) as typeof Ajv2020Mod;
const addFormats = ((addFormatsMod as unknown as { default?: unknown }).default ?? addFormatsMod) as typeof addFormatsMod;
const standalone = ((standaloneMod as unknown as { default?: unknown }).default ?? standaloneMod) as typeof standaloneMod;

const dir = new URL("../", import.meta.url);
const load = (n: string) => JSON.parse(readFileSync(new URL(`schemas/${n}.schema.json`, dir), "utf8"));
const ajv = new Ajv2020({ allErrors: true, strict: true, strictTypes: false, allowUnionTypes: true, code: { source: true, esm: true, lines: false } });
addFormats(ajv, ["date-time"]);
const map: Record<string, string> = { validateGraph: "graph", validateEvent: "event", validateIngestEvent: "ingest-event", validateSceneProposal: "scene-proposal" };
for (const [, n] of Object.entries(map)) ajv.addSchema(load(n), n);
let code = standalone(ajv, Object.fromEntries(Object.entries(map).map(([k, v]) => [k, v])));
// Make the output dependency-free (browser + node, no CommonJS require).
const helpers = `
const __dk_dateTime = (() => {
  const RE = /^\\d{4}-\\d{2}-\\d{2}[Tt ]\\d{2}:\\d{2}:\\d{2}(?:\\.\\d+)?(?:[Zz]|[+-]\\d{2}:?\\d{2})$/;
  return { validate: (s) => typeof s === "string" && RE.test(s) && !Number.isNaN(Date.parse(s)), compare: (a, b) => Date.parse(a) - Date.parse(b) };
})();
function __dk_equal(a, b) {
  if (a === b) return true;
  if (a && b && typeof a === "object" && typeof b === "object") {
    if (Array.isArray(a) !== Array.isArray(b)) return false;
    const ka = Object.keys(a), kb = Object.keys(b);
    if (ka.length !== kb.length) return false;
    for (const k of ka) if (!Object.prototype.hasOwnProperty.call(b, k) || !__dk_equal(a[k], b[k])) return false;
    return true;
  }
  return a !== a && b !== b;
}
function __dk_ucs2length(str) { let n = 0; for (const _ of str) n++; return n; }
`;
code = code
  .replace(/require\("ajv-formats\/dist\/formats"\)\.fullFormats\["date-time"\]/g, "__dk_dateTime")
  .replace(/require\("ajv\/dist\/runtime\/equal"\)\.default/g, "__dk_equal")
  .replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, "__dk_ucs2length")
  .replace('"use strict";', '"use strict";' + helpers);
if (/require\(/.test(code)) throw new Error("generated validators still contain require()");
code = "// GENERATED by packages/contracts/scripts/generate-validators.ts — do not edit.\n// @ts-nocheck\n/* eslint-disable */\n" + code;
writeFileSync(new URL("src/generated/validators.js", dir), code);
console.log("wrote packages/contracts/src/generated/validators.js", code.length, "bytes");
